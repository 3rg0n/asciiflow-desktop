use gpui::{IntoElement, PathBuilder, Styled, canvas, point, px, rgb};

#[derive(Clone, Copy)]
pub enum Icon {
    Select,
    Box,
    Line,
    Arrow,
    Draw,
    Text,
    Erase,
    New,
    Undo,
    Redo,
    Open,
    Export,
    Copy,
    Document,
    Grid,
    Minus,
    Plus,
}

impl Icon {
    pub fn element(self, color: u32) -> impl IntoElement {
        canvas(
            |_, _, _| (),
            move |bounds, (), window, _| {
                let mut path = PathBuilder::stroke(px(1.4));
                for (start, tail) in self
                    .strokes()
                    .iter()
                    .filter_map(|stroke| stroke.split_first())
                {
                    path.move_to(bounds.origin + point(px(start.0), px(start.1)));
                    for &(x, y) in tail {
                        path.line_to(bounds.origin + point(px(x), px(y)));
                    }
                }
                if let Ok(path) = path.build() {
                    window.paint_path(path, rgb(color));
                }
            },
        )
        .size(px(16.0))
        .flex_shrink_0()
    }

    fn strokes(self) -> &'static [&'static [(f32, f32)]] {
        match self {
            Self::Select => &[
                &[(3., 6.), (3., 3.), (6., 3.)],
                &[(10., 3.), (13., 3.), (13., 6.)],
                &[(13., 10.), (13., 13.), (10., 13.)],
                &[(6., 13.), (3., 13.), (3., 10.)],
            ],
            Self::Box => &[&[
                (2.5, 3.5),
                (13.5, 3.5),
                (13.5, 12.5),
                (2.5, 12.5),
                (2.5, 3.5),
            ]],
            Self::Line => &[&[(3., 13.), (13., 3.)]],
            Self::Arrow => &[&[(3., 13.), (13., 3.)], &[(8., 3.), (13., 3.), (13., 8.)]],
            Self::Draw => &[
                &[
                    (3., 13.),
                    (4.1, 9.1),
                    (10.7, 2.5),
                    (13.5, 5.3),
                    (6.9, 11.9),
                    (3., 13.),
                ],
                &[(9.1, 4.1), (11.9, 6.9)],
            ],
            Self::Text => &[
                &[(3.5, 4.), (12.5, 4.)],
                &[(8., 4.), (8., 13.)],
                &[(5.5, 13.), (10.5, 13.)],
            ],
            Self::Erase => &[
                &[
                    (2.5, 9.6),
                    (9.4, 2.7),
                    (13.8, 7.1),
                    (7.7, 13.2),
                    (6.1, 13.2),
                    (2.5, 9.6),
                ],
                &[(5.5, 6.6), (10., 10.9)],
                &[(7.8, 13.2), (14., 13.2)],
            ],
            Self::New => &[
                &[
                    (8., 13.5),
                    (3.5, 13.5),
                    (3.5, 2.5),
                    (9., 2.5),
                    (12.5, 6.),
                    (12.5, 7.5),
                ],
                &[(9., 2.5), (9., 6.), (12.5, 6.)],
                &[(11.5, 9.), (11.5, 14.)],
                &[(9., 11.5), (14., 11.5)],
            ],
            Self::Undo => &[
                &[(6., 3.5), (2.5, 7.), (6., 10.5)],
                &[(2.5, 7.), (9.5, 7.), (12., 8.), (13., 10.), (13., 12.5)],
            ],
            Self::Redo => &[
                &[(10., 3.5), (13.5, 7.), (10., 10.5)],
                &[(13.5, 7.), (6.5, 7.), (4., 8.), (3., 10.), (3., 12.5)],
            ],
            Self::Open => &[
                &[
                    (2.5, 12.5),
                    (2.5, 4.),
                    (6.5, 4.),
                    (8., 5.5),
                    (13., 5.5),
                    (13., 7.5),
                ],
                &[
                    (2.5, 12.5),
                    (4.5, 7.5),
                    (14.5, 7.5),
                    (12.5, 12.5),
                    (2.5, 12.5),
                ],
            ],
            Self::Export => &[
                &[(3., 9.5), (3., 13.), (13., 13.), (13., 9.5)],
                &[(8., 2.5), (8., 10.)],
                &[(5., 7.), (8., 10.), (11., 7.)],
            ],
            Self::Copy => &[
                &[(6., 6.), (13., 6.), (13., 13.), (6., 13.), (6., 6.)],
                &[(3., 10.), (3., 3.), (10., 3.)],
            ],
            Self::Document => &[
                &[
                    (4., 2.5),
                    (9.5, 2.5),
                    (13., 6.),
                    (13., 13.5),
                    (4., 13.5),
                    (4., 2.5),
                ],
                &[(9.5, 2.5), (9.5, 6.), (13., 6.)],
                &[(6., 9.), (11., 9.)],
                &[(6., 11.2), (10., 11.2)],
            ],
            Self::Grid => &[
                &[(3., 3.), (13., 3.), (13., 13.), (3., 13.), (3., 3.)],
                &[(3., 8.), (13., 8.)],
                &[(8., 3.), (8., 13.)],
            ],
            Self::Minus => &[&[(3.5, 8.), (12.5, 8.)]],
            Self::Plus => &[&[(3.5, 8.), (12.5, 8.)], &[(8., 3.5), (8., 12.5)]],
        }
    }
}
